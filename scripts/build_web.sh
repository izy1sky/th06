#!/usr/bin/env bash
# Builds the browser version into dist/.
#
#   scripts/build_web.sh <game folder>          # release build
#   DEBUG=1 scripts/build_web.sh <game folder>  # assertions and symbols
#
# <game folder> holds your 紅魔郷*.DAT files, msgothic.ttc and, for music, bgm/th06_XX.wav
# (or .ogg). Needs emsdk activated (source <emsdk>/emsdk_env.sh), python3, and ffmpeg with
# libvorbis or oggenc to turn WAV music into OGG. Windows: scripts/build_web.ps1.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/dist"
CACHE="$ROOT/build/web-bgm"

die() { echo "error: $*" >&2; exit 1; }

[ $# -eq 1 ] || die "usage: scripts/build_web.sh <game folder>"
GAME="$(cd "$1" 2>/dev/null && pwd)" || die "$1 is not a folder"

command -v em++ >/dev/null || die "em++ not found. Activate emsdk first: source <emsdk>/emsdk_env.sh"
command -v python3 >/dev/null || die "python3 not found"

DATS=(紅魔郷CM.DAT 紅魔郷ED.DAT 紅魔郷IN.DAT 紅魔郷MD.DAT 紅魔郷ST.DAT 紅魔郷TL.DAT)
for f in "${DATS[@]}" msgothic.ttc; do
  [ -f "$GAME/$f" ] || die "$GAME/$f is missing"
done

# The shaders are compiled into the game as byte arrays. premake writes this header for the
# desktop builds; write it here so the web build doesn't need premake.
mkdir -p "$ROOT/src/autogenerated"
python3 - "$ROOT/src" <<'EOF'
import sys
src = sys.argv[1]
with open(f"{src}/autogenerated/Embeds.hpp", "w") as out:
    out.write("#pragma once\n")
    for name, var in (("ff.vert", "vertShaderBytes"), ("ff.frag", "fragShaderBytes")):
        data = open(f"{src}/graphics/{name}", "rb").read().replace(b"\r\n", b"\n")
        out.write(f"\nstatic char {var}[] = {{" + "".join(f"0x{b:X}, " for b in data) + "0};\n")
EOF

# The web build plays OGG music (WAV is about 7x larger). Convert each WAV once into build/web-bgm/.
to_ogg() {
  if ffmpeg -hide_banner -encoders 2>/dev/null | grep -q libvorbis; then
    ffmpeg -loglevel error -y -i "$1" -c:a libvorbis -q:a 6 "$2"
  elif command -v oggenc >/dev/null; then
    oggenc -Q -q 6 -o "$2" "$1"
  else
    die "converting WAV music needs ffmpeg with libvorbis or oggenc (macOS: brew install vorbis-tools)"
  fi
}

echo "Copying game files from $GAME"
rm -rf "$OUT/assets"
mkdir -p "$OUT/assets/bgm" "$CACHE"
for f in "${DATS[@]}" msgothic.ttc NotoSansJP-Regular.ttf; do
  if [ -f "$GAME/$f" ]; then cp "$GAME/$f" "$OUT/assets/"; fi
done
music=0
for i in $(seq -w 1 17); do
  name="th06_$i"
  if [ -f "$GAME/bgm/$name.ogg" ]; then
    cp "$GAME/bgm/$name.ogg" "$OUT/assets/bgm/"
  elif [ -f "$GAME/bgm/$name.wav" ]; then
    if [ ! -f "$CACHE/$name.ogg" ] || [ "$GAME/bgm/$name.wav" -nt "$CACHE/$name.ogg" ]; then
      echo "  converting bgm/$name.wav to OGG"
      to_ogg "$GAME/bgm/$name.wav" "$CACHE/$name.tmp.ogg"
      mv "$CACHE/$name.tmp.ogg" "$CACHE/$name.ogg"
    fi
    cp "$CACHE/$name.ogg" "$OUT/assets/bgm/"
  else
    continue
  fi
  music=$((music + 1))
done
[ "$music" -gt 0 ] || echo "warning: no bgm/th06_XX.wav or .ogg in $GAME, the web version will have no music"

# play.html fetches every file listed here into the game's in-memory file system.
(cd "$OUT/assets" && find . -type f ! -name manifest.txt | sed 's|^\./||' | LC_ALL=C sort) > "$OUT/assets/manifest.txt"

if [ "${DEBUG:-0}" = "1" ]; then
  OPT_FLAGS=(-O0 -g -sASSERTIONS=2 -sSTACK_OVERFLOW_CHECK=2 -sGL_ASSERTIONS=1 -sGL_DEBUG=1)
else
  OPT_FLAGS=(-O2)
fi

# The same sources as premake5.lua, with the silent MIDI backend: the browser has no MIDI output.
SOURCES=("$ROOT"/src/*.cpp "$ROOT"/src/graphics/*.cpp "$ROOT"/src/pbg3/*.cpp "$ROOT"/src/thirdparty/*.cpp
  "$ROOT"/src/midi/MidiDefault.cpp)

echo "Compiling (about a minute)"
em++ -std=c++20 -I"$ROOT/src" "${OPT_FLAGS[@]}" \
  -sUSE_SDL=2 -sUSE_SDL_IMAGE=2 -sSDL2_IMAGE_FORMATS='["png","jpg"]' -sUSE_SDL_TTF=2 \
  -sFULL_ES2=1 -sMIN_WEBGL_VERSION=1 -sMAX_WEBGL_VERSION=2 \
  -sALLOW_MEMORY_GROWTH=1 -sEXIT_RUNTIME=0 -sFORCE_FILESYSTEM=1 \
  -sEXPORTED_RUNTIME_METHODS='["FS","addRunDependency","removeRunDependency","callMain"]' \
  -w \
  "${SOURCES[@]}" -o "$OUT/th06.js"

cp "$ROOT/web/play.html" "$OUT/index.html"

largest=$(python3 -c 'import os, sys; print(max(os.path.getsize(os.path.join(d, f)) for d, _, fs in os.walk(sys.argv[1]) for f in fs) // 1048576)' "$OUT/assets")
echo
echo "Done: $OUT ($music music tracks, largest file $largest MB)"
echo "Play it locally:  python3 -m http.server -d '$OUT' 8000   then open http://localhost:8000/"
echo "To publish it, upload everything in dist/."
