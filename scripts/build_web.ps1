# Builds the browser version into dist\. Windows version of scripts/build_web.sh.
#
#   powershell -ExecutionPolicy Bypass -File scripts\build_web.ps1 -Game C:\games\th06 -Emsdk C:\emsdk
#
# -Game     your game folder: the six DAT files, msgothic.ttc and, for music, bgm\th06_XX.wav (or .ogg)
# -Emsdk    the emsdk folder; not needed if emsdk_env.ps1 already ran in this window
# -DebugBuild  assertions and symbols
#
# Converting WAV music to OGG needs ffmpeg (with libvorbis) on PATH.
param(
    [Parameter(Mandatory = $true)][string]$Game,
    [string]$Emsdk,
    [switch]$DebugBuild
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
$Out = Join-Path $Root "dist"
$Cache = Join-Path $Root "build\web-bgm"

function Fail($Message) { Write-Host "error: $Message" -ForegroundColor Red; exit 1 }

if (-not (Test-Path $Game -PathType Container)) { Fail "$Game is not a folder" }
$Game = (Resolve-Path $Game).Path

if ($Emsdk) {
    if (-not (Test-Path (Join-Path $Emsdk "emsdk_env.ps1"))) { Fail "$Emsdk has no emsdk_env.ps1" }
    $env:EMSDK_QUIET = "1"
    & (Join-Path $Emsdk "emsdk_env.ps1") | Out-Null
}
if (-not (Get-Command em++ -ErrorAction SilentlyContinue)) {
    Fail "em++ not found. Pass -Emsdk <emsdk folder>, or run <emsdk>\emsdk_env.ps1 in this window first"
}

# This file stays ASCII so Windows PowerShell 5 reads it correctly, so the Japanese DAT names
# are built from their code points: "Kou Ma Kyou" + CM.DAT and so on.
$Prefix = -join [char[]](0x7D05, 0x9B54, 0x90F7)
$Dats = "CM", "ED", "IN", "MD", "ST", "TL" | ForEach-Object { "$Prefix$_.DAT" }
foreach ($f in $Dats + "msgothic.ttc") {
    if (-not (Test-Path -LiteralPath (Join-Path $Game $f))) { Fail "$Game\$f is missing" }
}

# The shaders are compiled into the game as byte arrays. premake writes this header for the
# desktop builds; write it here so the web build doesn't need premake.
$Src = Join-Path $Root "src"
New-Item -ItemType Directory -Force (Join-Path $Src "autogenerated") | Out-Null
$Header = New-Object System.Text.StringBuilder "#pragma once`n"
foreach ($pair in @(@("ff.vert", "vertShaderBytes"), @("ff.frag", "fragShaderBytes"))) {
    $bytes = [IO.File]::ReadAllBytes((Join-Path $Src "graphics\$($pair[0])"))
    [void]$Header.Append("`nstatic char $($pair[1])[] = {")
    foreach ($b in $bytes) { if ($b -ne 13) { [void]$Header.Append(("0x{0:X}, " -f $b)) } }
    [void]$Header.Append("0};`n")
}
[IO.File]::WriteAllText((Join-Path $Src "autogenerated\Embeds.hpp"), $Header.ToString())

# The web build plays OGG music (WAV is about 7x larger). Convert each WAV once into build\web-bgm\.
function Convert-ToOgg($Wav, $Ogg) {
    if (-not (Get-Command ffmpeg -ErrorAction SilentlyContinue)) { Fail "converting WAV music needs ffmpeg on PATH" }
    if (-not (ffmpeg -hide_banner -encoders 2>$null | Select-String libvorbis)) { Fail "your ffmpeg has no libvorbis encoder" }
    ffmpeg -loglevel error -y -i $Wav -c:a libvorbis -q:a 6 "$Ogg.tmp.ogg"
    if ($LASTEXITCODE -ne 0) { Fail "ffmpeg could not convert $Wav" }
    Move-Item -Force "$Ogg.tmp.ogg" $Ogg
}

Write-Host "Copying game files from $Game"
$Assets = Join-Path $Out "assets"
if (Test-Path $Assets) { Remove-Item -Recurse -Force $Assets }
New-Item -ItemType Directory -Force (Join-Path $Assets "bgm"), $Cache | Out-Null
foreach ($f in $Dats + "msgothic.ttc", "NotoSansJP-Regular.ttf") {
    $path = Join-Path $Game $f
    if (Test-Path -LiteralPath $path) { Copy-Item -LiteralPath $path $Assets }
}
$Music = 0
foreach ($i in 1..17) {
    $name = "th06_{0:D2}" -f $i
    $ogg = Join-Path $Game "bgm\$name.ogg"
    $wav = Join-Path $Game "bgm\$name.wav"
    $cached = Join-Path $Cache "$name.ogg"
    if (Test-Path $ogg) {
        Copy-Item $ogg (Join-Path $Assets "bgm")
    } elseif (Test-Path $wav) {
        if (-not (Test-Path $cached) -or (Get-Item $wav).LastWriteTime -gt (Get-Item $cached).LastWriteTime) {
            Write-Host "  converting bgm\$name.wav to OGG"
            Convert-ToOgg $wav $cached
        }
        Copy-Item $cached (Join-Path $Assets "bgm")
    } else {
        continue
    }
    $Music++
}
if ($Music -eq 0) { Write-Host "warning: no bgm\th06_XX.wav or .ogg in $Game, the web version will have no music" -ForegroundColor Yellow }

# play.html fetches every file listed here into the game's in-memory file system. Forward
# slashes, \n line endings, UTF-8 without a BOM.
$Files = Get-ChildItem -Recurse -File $Assets | ForEach-Object { $_.FullName.Substring($Assets.Length + 1) -replace '\\', '/' }
$Manifest = (($Files | Sort-Object -CaseSensitive) -join "`n") + "`n"
[IO.File]::WriteAllText((Join-Path $Assets "manifest.txt"), $Manifest, (New-Object System.Text.UTF8Encoding $false))

if ($DebugBuild) {
    $OptFlags = "-O0", "-g", "-sASSERTIONS=2", "-sSTACK_OVERFLOW_CHECK=2", "-sGL_ASSERTIONS=1", "-sGL_DEBUG=1"
} else {
    $OptFlags = @("-O2")
}

# The same sources as premake5.lua, with the silent MIDI backend: the browser has no MIDI output.
$Sources = @("*.cpp", "graphics\*.cpp", "pbg3\*.cpp", "thirdparty\*.cpp", "midi\MidiDefault.cpp") |
    ForEach-Object { Get-ChildItem (Join-Path $Src $_) } | ForEach-Object { $_.FullName }

# Plain comma lists instead of JSON: PowerShell strips the double quotes inside a JSON list.
$EmArgs = @("-std=c++20", "-I$Src") + $OptFlags + @(
    "-sUSE_SDL=2", "-sUSE_SDL_IMAGE=2", "-sSDL2_IMAGE_FORMATS=png,jpg", "-sUSE_SDL_TTF=2",
    "-sFULL_ES2=1", "-sMIN_WEBGL_VERSION=1", "-sMAX_WEBGL_VERSION=2",
    "-sALLOW_MEMORY_GROWTH=1", "-sEXIT_RUNTIME=0", "-sFORCE_FILESYSTEM=1",
    "-sEXPORTED_RUNTIME_METHODS=FS,addRunDependency,removeRunDependency,callMain",
    "-w"
) + $Sources + @("-o", (Join-Path $Out "th06.js"))

Write-Host "Compiling (about a minute)"
& em++ @EmArgs
if ($LASTEXITCODE -ne 0) { Fail "em++ failed" }

Copy-Item (Join-Path $Root "web\play.html") (Join-Path $Out "index.html")

$Largest = (Get-ChildItem -Recurse -File $Assets | Measure-Object Length -Maximum).Maximum
Write-Host ""
Write-Host ("Done: $Out ($Music music tracks, largest file {0:N0} MB)" -f ($Largest / 1MB)) -ForegroundColor Green
Write-Host "Play it locally:  powershell -ExecutionPolicy Bypass -File scripts\serve_web.ps1   then open http://localhost:8000/"
Write-Host "To publish it, upload everything in dist\."
